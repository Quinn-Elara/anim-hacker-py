#!/usr/bin/env python3
"""Generate src/animhacker/skeleton_data.py from the Second Life viewer's avatar_skeleton.xml
(indra/newview/character/avatar_skeleton.xml in https://github.com/secondlife/viewer).

The target offset calculator needs the default skeleton (bone hierarchy, local position, rotation
and scale, and the collision volumes). Rerun this script if Linden Lab ever changes the skeleton.

Usage:
    python3 tools/gen_skeleton.py PATH/TO/avatar_skeleton.xml src/animhacker/skeleton_data.py [note]
"""
import sys
import xml.etree.ElementTree as ET


def vec3(attr, node):
    parts = node.attrib[attr].split()
    if len(parts) != 3:
        raise ValueError("%s on %s is not a 3-vector: %r" % (attr, node.attrib.get("name"), node.attrib[attr]))
    return "(%s)" % ", ".join(repr(float(p)) for p in parts)


def collect(root):
    nodes = []

    def walk(element, parent_index):
        for child in element:
            if child.tag not in ("bone", "collision_volume"):
                raise ValueError("unexpected element <%s>" % child.tag)
            index = len(nodes)
            is_volume = child.tag == "collision_volume"
            nodes.append((
                child.attrib["name"],
                "" if is_volume else child.attrib.get("aliases", ""),
                parent_index,
                is_volume,
                vec3("pos", child),
                vec3("rot", child),
                vec3("scale", child),
            ))
            walk(child, index)

    walk(root, -1)
    return nodes


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    xml_path, out_path = argv[1], argv[2]
    note = argv[3] if len(argv) > 3 else "avatar_skeleton.xml"

    root = ET.parse(xml_path).getroot()
    if root.tag != "linden_skeleton":
        raise ValueError("not a linden_skeleton file")
    nodes = collect(root)
    bones = sum(1 for n in nodes if not n[3])
    volumes = sum(1 for n in nodes if n[3])
    if bones != int(root.attrib["num_bones"]) or volumes != int(root.attrib["num_collision_volumes"]):
        raise ValueError("node counts do not match the file header")

    lines = [
        '"""Default Second Life avatar skeleton.',
        "",
        "Generated by tools/gen_skeleton.py from %s." % note,
        "Do not edit by hand; rerun the script instead.",
        '"""',
        "",
        "BONE_COUNT = %d" % bones,
        "COLLISION_VOLUME_COUNT = %d" % volumes,
        "",
        "# (name, aliases, parent index (-1 for the root), is collision volume,",
        "#  local position in metres, local rotation as XYZ euler degrees, local scale)",
        "NODES = [",
    ]
    for name, aliases, parent, is_volume, pos, rot, scale in nodes:
        lines.append("    (%r, %r, %d, %s, %s, %s, %s)," % (name, aliases, parent, is_volume, pos, rot, scale))
    lines.append("]")

    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote %s (%d bones, %d collision volumes)" % (out_path, bones, volumes))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
